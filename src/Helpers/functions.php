if (!function_exists('__')) {
    function __(string $key, array $replace = []): string
    {
        $messages = translations();
        $lang = app_lang();
        $text = $messages[$lang][$key] ?? $messages['en'][$key] ?? $key;

        if (empty($replace)) {
            return $text;
        }

        $map = [];
        foreach ($replace as $k => $v) {
            $map[':' . $k] = (string) $v;
        }

        return strtr($text, $map);
    }
