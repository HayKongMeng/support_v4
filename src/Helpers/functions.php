if (!function_exists('app_lang')) {
    function app_lang(): string
    {
        static $resolved = null;
        if ($resolved !== null) {
            return $resolved;
        }

        $allowed = ['en', 'km'];
        $requested = strtolower((string)($_GET['lang'] ?? ''));
        $sessionLang = strtolower((string)($_SESSION['lang'] ?? ''));
        $cookieLang = strtolower((string)($_COOKIE['lang'] ?? ''));

        if (in_array($requested, $allowed, true)) {
            $resolved = $requested;
            if (session_status() === PHP_SESSION_ACTIVE) {
                $_SESSION['lang'] = $resolved;
            }
            setcookie('lang', $resolved, time() + (86400 * 365), '/');
            return $resolved;
        }

        if (in_array($sessionLang, $allowed, true)) {
            $resolved = $sessionLang;
            return $resolved;
        }

        if (in_array($cookieLang, $allowed, true)) {
            $resolved = $cookieLang;
            if (session_status() === PHP_SESSION_ACTIVE) {
                $_SESSION['lang'] = $resolved;
            }
            return $resolved;
        }

        $resolved = 'en';
        return $resolved;
    }
}

if (!function_exists('lang_url')) {
    function lang_url(string $lang): string
    {
        $lang = strtolower($lang);
        if (!in_array($lang, ['en', 'km'], true)) {
            $lang = 'en';
        }

        $uri = $_SERVER['REQUEST_URI'] ?? '/';
        $parts = parse_url($uri);
        $path = $parts['path'] ?? '/';
        $query = [];

        if (!empty($parts['query'])) {
            parse_str($parts['query'], $query);
        }

        $query['lang'] = $lang;
        $queryString = http_build_query($query);

        return $path . ($queryString ? '?' . $queryString : '');
    }
}

